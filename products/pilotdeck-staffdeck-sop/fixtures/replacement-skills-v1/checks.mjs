import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { createRequire } from 'node:module';
import { parse } from 'yaml';
import { createSkillModulePort, createSkillManagementPort } from '../../../../src/composition/domainPorts.js';
import { HttpModuleClient } from '../../../../src/composition/HttpModuleClient.js';
import { parseModulesConfig } from '../../../../src/pilot/config/parseModulesConfig.js';
import { renderGeneratedEntrypoint } from '../../../../scripts/generate-frontend-modules.mjs';
import { createModuleRuntimeRouter } from '../../../../ui/server/routes/modules.js';

const root = dirname(fileURLToPath(import.meta.url));
const express = createRequire(new URL('../../../../ui/package.json', import.meta.url))('express');
test('versioned non-K Skills fixture preserves public Ports, frontend selection and runtime projection', async t => {
  const env = { ...process.env, REPLACEMENT_SKILLS_PORT: '0' }; delete env.NODE_OPTIONS;
  const child = spawn(process.execPath, [join(root, 'runtime.mjs')], { env, stdio: ['ignore', 'pipe', 'inherit'] });
  t.after(() => new Promise(resolve => { child.once('close', resolve); child.kill('SIGTERM'); }));
  let output = '';
  const port = await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(Error('Fixture startup timed out')), 5000);
    child.on('error', reject);
    child.stdout.on('data', chunk => { output += chunk; if (output.includes('\n')) { clearTimeout(timeout); resolve(JSON.parse(output.split('\n')[0]).port); } });
  });
  const profile = parse(await readFile(join(root, 'profile.yaml'), 'utf8'));
  const diagnostics = [];
  const parsed = parseModulesConfig(profile.modules, root, diagnostics);
  assert.deepEqual(diagnostics, []);
  assert.equal(parsed.skills.implementationId, 'fixture.replacement-skills.v1');
  const binding = { ...parsed.skills, endpoint: `http://127.0.0.1:${port}` };
  const management = createSkillManagementPort(binding);
  const runtime = createSkillModulePort(binding);
  const listed = await management.list({});
  assert.equal(listed.items.length, 1); assert.equal(listed.items[0].slug, 'replacement-guide');
  assert.equal(listed.items[0].readonly, true);
  const read = await management.read({ scope: 'builtin', slug: 'replacement-guide' });
  assert.match(read.content, /REPLACEMENT-SKILLS-V1-4826/);
  assert.equal((await runtime.list({}))[0].name, 'replacement-guide');
  assert.equal(await runtime.read({ name: 'replacement-guide' }), read.content);
  await assert.rejects(management.read({ scope: 'builtin', slug: 'missing' }), error => error.code === 'SKILL_NOT_FOUND');
  await assert.rejects(management.create({ scope: 'user', slug: 'forbidden' }), error => error.code === 'MODULE_PROTOCOL_INCOMPATIBLE');
  const call = await new HttpModuleClient(binding).call({ runId: 'fixture', operationId: 'fixture', requestId: 'unknown', module: 'skills', payload: { operation: 'create', input: {} } });
  assert.equal(call.ok, false); assert.equal(call.error.code, 'MODULE_CAPABILITY_UNAVAILABLE');
  const wrong = new HttpModuleClient({ ...binding, implementationId: 'wrong.skills' });
  await assert.rejects(wrong.manifest(), error => error.code === 'MODULE_PROTOCOL_INCOMPATIBLE');
  const generated = renderGeneratedEntrypoint(profile);
  assert.match(generated, /modules\/pilotdeck-skills/);
  assert.match(generated, /fixture.replacement-skills.v1/);
  assert.doesNotMatch(generated, /modules\/(staffdeck-knowledge|fixture-knowledge-search)/);
  assert.doesNotMatch(generated, /19643/);
  const absent = structuredClone(profile); absent.modules.skills.enabled = false;
  assert.doesNotMatch(renderGeneratedEntrypoint(absent), /import .*pilotdeck-skills/);
  const app = express(); app.use('/api/modules', createModuleRuntimeRouter({ loadConfig: () => profile, getGateway: async () => ({}) }));
  const server = createServer(app); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const response = await fetch(`http://127.0.0.1:${server.address().port}/api/modules/runtime`);
  assert.equal(response.status, 200);
  const actual = (await response.json()).modules.skills;
  assert.deepEqual(actual, { enabled: true, implementationId: binding.implementationId, frontendModule: 'pilotdeck.skills',
    contract: 'pilotdeck.skills/v1', transport: 'module-http-v2', methods: ['list', 'read'] });
  assert.equal(actual.endpoint, undefined);
});
